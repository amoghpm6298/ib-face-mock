// Core graph shape, ported from journeysnudgesemi/emi-conversions-prototype.html
// (the 2026-09-25 graph rebuild) — already id/edge-based, not the older
// nested-children tree. Porting means field-name adaptation (`from`/`to`
// stay as-is here; React Flow's own `source`/`target` naming is applied
// only at the render-layer adapter, not in this canonical shape) and
// moving mutation from a global object to a reducer, not a structural
// redesign.

import type { DcNodeType } from './nodeMeta';

export interface DripNode {
  id: string;
  type: DcNodeType;
  label: string;
  meta: string;
  autoGenerated: boolean;
  // Raw pendingConfig snapshot from whichever drawer form built/last-edited
  // this node. A node without one (editing it shows blank fields instead
  // of the form pre-filled) should only ever be a transient mid-edit
  // state, never persisted seed/demo data — see seedCampaigns.ts for how
  // every seeded node's `_config` is reverse-engineered from its label/meta.
  _config?: Record<string, unknown> | null;
}

export interface DripEdge {
  id: string;
  from: string;
  // null = an open slot ("+" add-step button), not yet connected to a node.
  to: string | null;
  branchLabel: string;
  autoGenerated: boolean;
  // Stable branch identity for Random Split / Decision Split branches —
  // lets an edit that inserts/removes a branch reconcile by identity
  // instead of fragile array-position/count matching. Absent on edges
  // that predate this (legacy branches); the reducer backfills it lazily,
  // same behavior as the original.
  branchId?: string;
}

export interface DripGraph {
  nodes: Record<string, DripNode>;
  edges: DripEdge[];
  rootId: string | null;
}

export interface DripGoalCondition {
  attribute: string;
  operator: string;
  value?: string;
  values?: string[];
  value2?: string;
}

// Shared by Condition's "Transaction history" source and Entry · Audience's
// own optional transaction-history block, so the two entry points can't
// drift — one config shape, one UI component, two call sites. The builder
// only ever captures this as config; nothing executes it (see the Node
// Reference's Known Limitations / Transaction-history condition section).
export interface DripTxnHistoryCriteria {
  filters: DripGoalCondition[];
  lookbackDuration: number;
  lookbackUnit: 'days' | 'hours';
  existence: 'exists' | 'none';
}

// Shared by Entry · Audience's entity = 'Milestone' block, Condition's
// "Milestone" source, and Branch's "Milestone" source — one specific,
// already-configured milestone benefit, checked either as Completed/Not
// Completed (operator 'IS', value auto-set to "100" same as the real
// form) or via a numeric/percentage comparator against its progress.
// value2 is only meaningful for 'BETWEEN'. See sharedConstants.ts's
// MILESTONE_BENEFITS/MILESTONE_OPERATORS for where this is grounded.
export interface DripMilestoneCondition {
  benefitId: string;
  operator: string;
  value?: string;
  value2?: string;
  statusChoice?: 'COMPLETED' | 'NOT_COMPLETED';
}

// Entry · Audience's entity-scoped filter blocks — the primary block and
// every block in extraEntityGroups share this one shape, repeatable and
// AND'd together (e.g. Account = Dormant AND Card = Active). Reconsidered
// twice before landing here: first kept Transaction-history as a wholly
// separate toggle (on the claim it couldn't share this shape at all);
// then as a separate "kind" in a tagged union (on the claim it at least
// needed a different shape). Neither holds up — Transaction is just
// another entity, its attributes already exist in ELIGIBILITY_META, and
// ConditionRows already renders them. The only things an entity made of
// many-records-per-member (Transaction) needs that a one-row-per-member
// entity (Customer/Account/Card) doesn't are a lookback window and an
// existence direction — three optional fields, not a different shape.
// They're simply unused/meaningless whenever entity isn't 'Transaction'.
export interface DripEntityConditionGroup {
  entity: string;
  conditions: DripGoalCondition[];
  lookbackDuration?: number;
  lookbackUnit?: 'days' | 'hours';
  existence?: 'exists' | 'none';
  // Only meaningful when entity = 'Milestone' — same "extra optional
  // fields, not a different shape" precedent as Transaction's lookback/
  // existence above. `conditions` is simply unused for this entity.
  milestone?: DripMilestoneCondition;
}

// One filter row: what, comparison, value. The single shape behind Entry ·
// Audience, Condition and Branch, replacing the Entity control, the Source
// control and the separate per-source forms that sat behind them.
//
// `group` + `field` together are the "what". For Account/Card/Customer the
// field is an attribute name and the row is self-contained. The other three
// groups keep the shape their question always needed, carried on the same
// row rather than in a different form:
//   Transactions      — `operator` is the existence direction, `txn` holds
//                       the transaction fields and the lookback.
//   Milestone         — `field` is the benefit id, `operator` is a real
//                       MILESTONE_OPERATORS code, `value`/`value2` the
//                       progress comparison.
//   Previous message  — `values` holds the delivery statuses that count.
//
// Rows on one step are AND'd. Branch is the exception by nature: it shares
// one row's `group`/`field` across its arms, and each arm carries its own
// comparison and value, because it routes rather than narrows.
export interface DripFilterRow {
  group: string;
  field: string;
  operator?: string;
  value?: string;
  value2?: string;
  values?: string[];
  txn?: DripTxnHistoryCriteria;
  // Milestone only: whether the typed progress is a percent or a rupee
  // amount. Percent is the default, and "is at least 100%" is how completed
  // is expressed — there is no Completed/Not Completed choice.
  valueUnit?: 'percent' | 'rupees';
  // App activity only: the chosen event's own details, keyed by detail kind
  // (today only 'offer'). A detail left out, or left empty, means any value.
  // Kept as a map so a new detail kind needs no new field.
  details?: Record<string, string>;
}

export interface DripGoal {
  eventCategory: string;
  eventType: string;
  conditions: DripGoalCondition[];
  // Journey/Offer Events' own scoping — which journey/batch or offer
  // type/name this event is about. Optional and only meaningful for
  // those two categories; absent (not just empty-string) on every other
  // category and on every campaign saved before this existed. Entry ·
  // Event and Wait for Event carry the identical pair of optional fields
  // directly on their own _config (untyped, same as every other node
  // config in this app), not here — this interface only covers Goal.
  journey?: string;
  batch?: string;
  offerType?: string;
  offerName?: string;
  // A card event's own details, where it has any (Card hotlisted carries a
  // reason, Card control updated a channel and what changed). Entry · Event
  // and Wait for Event carry the identical key on their own untyped
  // _config. Absent on every campaign saved before this existed, and an
  // empty detail means any value.
  cardDetails?: Record<string, string>;
}

export type DripCampaignStatus =
  | 'DRAFT' | 'PENDING_REVIEW' | 'ACTIVE' | 'SCHEDULED' | 'PAUSED' | 'KILLED' | 'CHANGES_REQUESTED';

export interface DripCampaign {
  id: string;
  name: string;
  description?: string;
  issuer: string;
  // When true, `programs` is ignored — scope is every current and future
  // program under this issuer, not a fixed list.
  applyToAllPrograms?: boolean;
  programs: string[];
  goal: DripGoal | null;
  controlPct: number;
  status: DripCampaignStatus;
  root: DripGraph | null;
  startDate?: string;
  endDate?: string;
  versionOf?: string | null;
  // Re-entry — can a customer who already reached a terminal node (Exit
  // or Goal Reached) on a previous run of THIS campaign be swept back in
  // on a later qualifying run? Off by default, matching today's de facto
  // behavior (no existing campaign has ever had a concept of re-entry).
  // Cool-off only has meaning when allowReEntry is true; 0 = immediate.
  allowReEntry?: boolean;
  reEntryCooloffDuration?: number;
  reEntryCooloffUnit?: 'days' | 'hours';
  // Guardrails — exclusion lists checked continuously, at every node, not
  // just at entry (unlike re-entry, which is a one-time gate). Kept as a
  // small keyed object rather than a flat field per list so adding a new
  // exclusion type later is one more key, not a new top-level field.
  guardrails?: { dnc: boolean; npa: boolean };
}
