// Regression tests for the explicit hard-constraint registry.
//
// The defect, proven in the audit: the set of hard constraints the validator
// knew about was IMPLICIT — whichever checks happened to push an entry. A
// constraint with no check produced no record, and a record's absence was
// indistinguishable from a pass. A campaign sending on RCS, which the bank
// context marks available: false, came back PRE-VALIDATED with five
// applicable hard constraints never represented at all.
//
// The registry inverts the default: every known constraint starts at
// 'not-run' and a check can only improve on that.
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateCampaignGraph } from './validate';
import { initialHardConstraints, isApplicable } from './hardConstraints';
import { dcDefaultConfig } from '../src/reducer/defaultConfig';
import type { DripGraph } from '../src/data/graphTypes';
import type { DcNodeType } from '../src/data/nodeMeta';

const here = dirname(fileURLToPath(import.meta.url));
const readJson = (p: string) => JSON.parse(readFileSync(resolve(here, p), 'utf8'));

const WINDOW = { from: '21:00', to: '09:00' };

const node = (id: string, type: DcNodeType, config: Record<string, unknown> = {}) => ({
  id,
  type,
  label: id,
  meta: '',
  autoGenerated: false,
  _config: config,
});
const edge = (id: string, from: string, to: string | null) => ({
  id,
  from,
  to,
  branchLabel: '',
  autoGenerated: false,
});

/** A structurally valid, single-Send campaign. `channel` and timing vary per test. */
function campaign(send: Record<string, unknown>): DripGraph {
  return {
    rootId: 'e1',
    nodes: {
      e1: node('e1', 'ENTRY_EVENT', { eventCategory: 'Transaction Events', eventType: 'Transaction' }),
      s1: node('s1', 'SEND', {
        ...(dcDefaultConfig('SEND', null) as Record<string, unknown>),
        channel: 'SMS',
        account: 'IBL-Karix-Txns',
        templateId: 'CT-3301',
        ...send,
      }),
      x1: node('x1', 'EXIT', { reason: 'done' }),
    },
    edges: [edge('a', 'e1', 's1'), edge('b', 's1', 'x1')],
  };
}

/** Timed at 11:00, which is outside the window — so quiet hours can PASS. */
const compliantSend = { timing: 'Absolute', absTime: '11:00' };
/** Fully configured: every constraint that HAS a check can actually run. */
const fullLimits = {
  maxMessagesPerCustomerPerCampaign: 4,
  quietHours: WINDOW,
  availableChannels: [
    { channel: 'SMS', available: true },
    { channel: 'EMAIL', available: true },
    { channel: 'RCS', available: false },
  ],
};

describe('the registry is complete and always present', () => {
  it('declares every hard constraint named in the audit', () => {
    const ids = initialHardConstraints().map((c) => c.id);
    // dnc / npa are deliberately NOT here: the application models them as
    // campaign-level user choices (GuardrailsStep.tsx), not issuer-level
    // hard constraints. They are handled as campaign configuration instead.
    expect(ids).toEqual([
      'channel-availability',
      'message-cap',
      'message-spacing',
      'quiet-hours',
      'event-freeze',
      'maker-checker',
    ]);
    expect(ids).not.toContain('dnc');
    expect(ids).not.toContain('npa');
  });

  it('every entry appears in the run record, whatever the campaign', () => {
    // Including the ones with no check implemented — the whole point.
    const report = validateCampaignGraph(campaign(compliantSend), undefined, fullLimits);
    expect(report.hardConstraints.map((c) => c.id)).toEqual(initialHardConstraints().map((c) => c.id));

    // And every one carries a reason, so none is a bare status.
    for (const c of report.hardConstraints) {
      expect(c.detail.length, `${c.id} has no detail`).toBeGreaterThan(0);
      expect(c.source.length, `${c.id} has no source`).toBeGreaterThan(0);
    }
  });

  it('starts every applicable constraint at not-run, never at pass', () => {
    for (const c of initialHardConstraints()) {
      if (isApplicable(c)) expect(c.status, `${c.id} must start unverified`).toBe('not-run');
    }
  });

  it('never claims an unimplemented constraint is enforced', () => {
    const report = validateCampaignGraph(campaign(compliantSend), undefined, fullLimits);
    // channel-availability left this list when it got a real check; dnc and
    // npa left the registry entirely (campaign-level user choices).
    for (const id of ['message-spacing', 'event-freeze']) {
      const c = report.hardConstraints.find((x) => x.id === id)!;
      expect(c.status, `${id} has no check yet`).toBe('not-run');
      expect(c.detail).toMatch(/No check implemented/);
      expect(c.executedBy).toBe('—');
    }
  });

  it('rejects an unknown constraint id rather than dropping the update', () => {
    // Guards the registry's own wiring: a typo'd id must not leave a
    // constraint silently at 'not-run' while looking connected.
    expect(() => validateCampaignGraph(campaign(compliantSend), undefined, fullLimits)).not.toThrow();
    expect(initialHardConstraints().find((c) => c.id === 'typo-id')).toBeUndefined();
  });
});

describe('outcome is derived from the registry', () => {
  it('an applicable unimplemented constraint downgrades the outcome to incomplete', () => {
    // Everything that HAS a check passes here, and the config for all three
    // is supplied. The outcome is still 'incomplete', because four applicable
    // constraints have no check at all — which is exactly the point: a
    // constraint cannot earn a pass by having nothing look at it.
    const report = validateCampaignGraph(campaign(compliantSend), undefined, fullLimits);

    expect(report.checks.every((c) => c.status === 'pass')).toBe(true);
    for (const id of ['message-cap', 'quiet-hours', 'channel-availability']) {
      expect(report.hardConstraints.find((c) => c.id === id)?.status, id).toBe('pass');
    }
    expect(report.unverifiedHardConstraints).toEqual(['message-spacing', 'event-freeze']);
    expect(report.outcome).toBe('incomplete');
  });

  it('pre-validated requires EVERY applicable constraint to have passed', () => {
    // The rule, stated as an invariant rather than as a specific scenario:
    // whatever the inputs, 'pre-validated' implies no applicable constraint
    // is left unverified or failed.
    const cases: DripGraph[] = [
      campaign(compliantSend),
      campaign({ timing: 'Absolute', absTime: '23:30' }),
      campaign({ timing: 'Relative', relativeAnchor: 'Entry' }),
    ];
    for (const g of cases) {
      for (const lim of [undefined, fullLimits, { maxMessagesPerCustomerPerCampaign: 4 }]) {
        const r = validateCampaignGraph(g, undefined, lim);
        if (r.outcome === 'pre-validated') {
          const applicable = r.hardConstraints.filter(isApplicable);
          expect(applicable.every((c) => c.status === 'pass')).toBe(true);
          expect(r.unverifiedHardConstraints).toEqual([]);
        }
      }
    }
  });

  it('not-applicable does not downgrade the outcome', () => {
    const report = validateCampaignGraph(campaign(compliantSend), undefined, fullLimits);
    const mc = report.hardConstraints.find((c) => c.id === 'maker-checker')!;

    expect(mc.status).toBe('not-applicable');
    // It is excluded from the unverified list...
    expect(report.unverifiedHardConstraints).not.toContain('maker-checker');
    // ...but it is NOT a pass, and says so. Nothing about it was verified.
    expect(mc.detail).toMatch(/this is not a pass/i);
    expect(mc.detail).toMatch(/fictional/);
    expect(mc.detail).toMatch(/re-classified/);
  });

  it('a confirmed failure outranks incompleteness', () => {
    // Over the cap, and five constraints unverified. 'failed' must win, so a
    // real violation is never softened into "we could not tell".
    const report = validateCampaignGraph(campaign(compliantSend), undefined, {
      maxMessagesPerCustomerPerCampaign: 0,
      quietHours: WINDOW,
    });
    expect(report.hardConstraints.find((c) => c.id === 'message-cap')?.status).toBe('fail');
    expect(report.unverifiedHardConstraints.length).toBeGreaterThan(0);
    expect(report.outcome).toBe('failed');
  });

  it('a registry failure alone is enough to fail the run', () => {
    // Even if no CheckResult failed, a 'fail' in the registry decides it.
    const report = validateCampaignGraph(campaign({ timing: 'Absolute', absTime: '03:00' }), undefined, fullLimits);
    expect(report.hardConstraints.find((c) => c.id === 'quiet-hours')?.status).toBe('fail');
    expect(report.outcome).toBe('failed');
  });
});

describe('the audit scenario that forced this change', () => {
  it('an RCS send cannot come back pre-validated', () => {
    // RCS is marked available: false in the bank context. When the registry
    // landed this was merely 'incomplete' (no check existed); now there is a
    // check, so it is a confirmed violation and the outcome is 'failed'.
    // Either way the point holds: it must never be pre-validated.
    const bank = readJson('context/bank-context.json');
    const rcs = bank.channels.available.find((c: { channel: string }) => c.channel === 'RCS');
    expect(rcs.available).toBe(false); // the premise, read from the context

    const report = validateCampaignGraph(campaign({ ...compliantSend, channel: 'RCS' }), undefined, {
      ...fullLimits,
      availableChannels: bank.channels.available,
    });

    expect(report.outcome).not.toBe('pre-validated');
    expect(report.outcome).toBe('failed');

    const ca = report.hardConstraints.find((c) => c.id === 'channel-availability')!;
    expect(ca.status).toBe('fail');
    expect(ca.detail).toMatch(/available: false/);
  });

  it('the bundled prose entry is gone, replaced by individual records', () => {
    const report = validateCampaignGraph(campaign(compliantSend), undefined, fullLimits);
    const everywhere = [...report.checks, ...report.unverified].map((c) => c.id);

    expect(everywhere).not.toContain('bank-constraint-enforcement');
    expect(everywhere).not.toContain('maker-checker-flag'); // moved into the registry
    // Of the four it used to bundle, the two that are genuinely issuer-level
    // are now individually identifiable; dnc/npa moved to campaign config.
    for (const id of ['message-spacing', 'event-freeze']) {
      expect(report.hardConstraints.map((c) => c.id)).toContain(id);
    }
    for (const id of ['dnc', 'npa']) {
      expect(report.hardConstraints.map((c) => c.id)).not.toContain(id);
      expect(report.unverifiedHardConstraints).not.toContain(id);
    }
  });
});

describe('hard-constraint metadata is consistent across branches', () => {
  it('message-cap identifies as a hard constraint whether it passes, fails or is skipped', () => {
    // It previously carried the marker ONLY when not-run, so the record
    // could not answer "which hard constraints were verified?".
    const pass = validateCampaignGraph(campaign(compliantSend), undefined, fullLimits);
    expect(pass.checks.find((c) => c.id === 'message-cap')?.hardConstraint).toBe(true);

    const fail = validateCampaignGraph(campaign(compliantSend), undefined, {
      maxMessagesPerCustomerPerCampaign: 0,
    });
    expect(fail.checks.find((c) => c.id === 'message-cap')?.hardConstraint).toBe(true);

    const skipped = validateCampaignGraph(campaign(compliantSend));
    expect(skipped.unverified.find((c) => c.id === 'message-cap')?.hardConstraint).toBe(true);
  });

  it('quiet-hours identifies as a hard constraint on all four of its branches', () => {
    const branches: { label: string; report: ReturnType<typeof validateCampaignGraph> }[] = [
      { label: 'pass', report: validateCampaignGraph(campaign(compliantSend), undefined, fullLimits) },
      {
        label: 'fail',
        report: validateCampaignGraph(campaign({ timing: 'Absolute', absTime: '03:00' }), undefined, fullLimits),
      },
      {
        label: 'undetermined',
        report: validateCampaignGraph(campaign({ timing: 'Relative', relativeAnchor: 'Entry' }), undefined, fullLimits),
      },
      { label: 'no window', report: validateCampaignGraph(campaign(compliantSend), undefined, { maxMessagesPerCustomerPerCampaign: 4 }) },
    ];

    for (const { label, report } of branches) {
      const entry = [...report.checks, ...report.unverified].find((c) => c.id === 'quiet-hours');
      expect(entry, `${label}: quiet-hours missing entirely`).toBeDefined();
      expect(entry?.hardConstraint, `${label}: not marked hard`).toBe(true);
      // And the registry agrees with the CheckResult on every branch.
      expect(report.hardConstraints.find((c) => c.id === 'quiet-hours')?.status).toBe(entry?.status);
    }
  });

  it('the registry status always agrees with the message-cap CheckResult', () => {
    for (const lim of [fullLimits, { maxMessagesPerCustomerPerCampaign: 0 }, undefined]) {
      const r = validateCampaignGraph(campaign(compliantSend), undefined, lim);
      const entry = [...r.checks, ...r.unverified].find((c) => c.id === 'message-cap')!;
      expect(r.hardConstraints.find((c) => c.id === 'message-cap')?.status).toBe(entry.status);
    }
  });
});
