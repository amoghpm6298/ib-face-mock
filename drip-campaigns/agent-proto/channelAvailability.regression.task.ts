// Regression tests for channel-availability validation.
//
// The gap this closes: the planner filtered unavailable channels when
// CHOOSING one, and nothing checked the finished campaign. The guarantee
// therefore rested entirely on the planner being correct — and the audit's
// probe proved a hand-built RCS campaign (RCS is marked available: false in
// the bank context) came back PRE-VALIDATED.
//
// So these tests deliberately construct invalid graphs by hand rather than
// going through the planner. A check that only ever sees planner output
// cannot demonstrate it would catch anything.
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { plan } from './planner';
import { validateCampaignGraph } from './validate';
import { assessChannels, availabilityConfigProblem, collectChannelUses } from './channelAvailability';
import { dcResetIdCounters } from '../src/reducer/idGen';
import { dcDefaultConfig } from '../src/reducer/defaultConfig';
import { CHANNEL_CONFIG_LABELS } from '../src/data/sharedConstants';
import type { DripGraph } from '../src/data/graphTypes';
import type { DcNodeType } from '../src/data/nodeMeta';

const here = dirname(fileURLToPath(import.meta.url));
const readJson = (p: string) => JSON.parse(readFileSync(resolve(here, p), 'utf8'));
const bankContext = () => readJson('context/bank-context.json');

/** The issuer's real list from the mock context: RCS is the unavailable one. */
const AVAILABLE = bankContext().channels.available;

const node = (id: string, type: DcNodeType, config: Record<string, unknown> = {}) => ({
  id,
  type,
  label: id,
  meta: '',
  autoGenerated: false,
  _config: config,
});
const edge = (id: string, from: string, to: string | null) => ({
  id,
  from,
  to,
  branchLabel: '',
  autoGenerated: false,
});

/** A structurally valid single-Send campaign; the Send config varies per test. */
function campaign(...sends: Record<string, unknown>[]): DripGraph {
  const nodes: DripGraph['nodes'] = {
    e1: node('e1', 'ENTRY_EVENT', { eventCategory: 'Transaction Events', eventType: 'Transaction' }),
    x1: node('x1', 'EXIT', { reason: 'done' }),
  };
  const edges = [];
  let prev = 'e1';
  sends.forEach((s, i) => {
    const id = `s${i + 1}`;
    nodes[id] = node(id, 'SEND', {
      ...(dcDefaultConfig('SEND', null) as Record<string, unknown>),
      channel: 'SMS',
      account: 'IBL-Karix-Txns',
      templateId: 'CT-3301',
      timing: 'Absolute',
      absTime: '11:00',
      ...s,
    });
    edges.push(edge(`e-${id}`, prev, id));
    prev = id;
  });
  edges.push(edge('e-exit', prev, 'x1'));
  return { rootId: 'e1', nodes, edges };
}

const limits = (availableChannels?: unknown) => ({
  maxMessagesPerCustomerPerCampaign: 4,
  quietHours: { from: '21:00', to: '09:00' },
  ...(availableChannels !== undefined ? { availableChannels } : {}),
});

/** Distinguishes "pass undefined as the config" from "omit the field entirely"
 *  — passing `undefined` would otherwise re-trigger the default below. */
const OMIT = Symbol('omit');

const caCheck = (graph: DripGraph, available: unknown = AVAILABLE) => {
  const report = validateCampaignGraph(graph, undefined, available === OMIT ? limits() : limits(available));
  return {
    report,
    ran: report.checks.find((c) => c.id === 'channel-availability'),
    skipped: report.unverified.find((c) => c.id === 'channel-availability'),
    registry: report.hardConstraints.find((c) => c.id === 'channel-availability')!,
  };
};

describe('channel availability — the happy path', () => {
  it('passes when every Send uses an available channel', () => {
    const { ran, registry } = caCheck(campaign({ channel: 'SMS' }, { channel: 'EMAIL' }));
    expect(ran?.status).toBe('pass');
    expect(registry.status).toBe('pass');
    expect(ran?.detail).toMatch(/all 2 channel use\(s\).*are marked available/);
    expect(ran?.hardConstraint).toBe(true);
  });

  it('passes a campaign with no Sends at all', () => {
    const empty: DripGraph = {
      rootId: 'e1',
      nodes: {
        e1: node('e1', 'ENTRY_EVENT', { eventCategory: 'Transaction Events', eventType: 'Transaction' }),
        x1: node('x1', 'EXIT', { reason: 'done' }),
      },
      edges: [edge('a', 'e1', 'x1')],
    };
    const { ran } = caCheck(empty);
    expect(ran?.status).toBe('pass');
    expect(ran?.detail).toMatch(/no Send nodes/);
  });

  it('treats an empty fallbackChannel as "no fallback", not as a bad channel', () => {
    // dcDefaultConfig ships fallbackChannel: '' on every Send, and
    // dcAddFormValid's own `if (!p.fallbackChannel) return true` confirms
    // empty means unconfigured. Counting it would fail every normal campaign.
    const uses = collectChannelUses(campaign({ channel: 'SMS', fallbackChannel: '' }));
    expect(uses).toHaveLength(1);
    expect(uses[0].role).toBe('primary');
    expect(caCheck(campaign({ channel: 'SMS', fallbackChannel: '' })).ran?.status).toBe('pass');
  });
});

describe('channel availability — confirmed violations', () => {
  it('fails a deliberately constructed RCS send, which the planner would never produce', () => {
    const rcs = AVAILABLE.find((c: { channel: string }) => c.channel === 'RCS');
    expect(rcs.available).toBe(false); // premise, read from the context

    const { report, ran, registry } = caCheck(campaign({ channel: 'RCS' }));
    expect(ran?.status).toBe('fail');
    expect(registry.status).toBe('fail');
    expect(ran?.detail).toMatch(/s1 "s1" \(primary: RCS\) — the issuer marks this channel available: false/);
    expect(report.outcome).toBe('failed');
  });

  it('catches an unavailable FALLBACK channel, not just the primary', () => {
    // The fallback is a real delivery route — it is what actually delivers
    // when the primary fails. Checking only `channel` would miss this.
    const { report, ran } = caCheck(campaign({ channel: 'SMS', fallbackChannel: 'RCS' }));
    expect(ran?.status).toBe('fail');
    expect(ran?.detail).toMatch(/\(fallback: RCS\)/);
    expect(report.outcome).toBe('failed');
  });

  it('fails a channel the issuer does not list at all', () => {
    // Real app channel, but absent from this issuer's configuration, so it
    // is not known to be available. Defaulting it to available would be the
    // silent-pass failure this whole exercise exists to remove.
    const onlySms = [{ channel: 'SMS', available: true }];
    const { report, ran } = caCheck(campaign({ channel: 'WHATSAPP' }), onlySms);
    expect(ran?.status).toBe('fail');
    expect(ran?.detail).toMatch(/not present in the issuer's channels.available list/);
    expect(report.outcome).toBe('failed');
  });

  it('fails a channel the application does not recognise', () => {
    const { ran } = caCheck(campaign({ channel: 'CARRIER_PIGEON' }));
    expect(ran?.status).toBe('fail');
    expect(ran?.detail).toMatch(/not a channel this application recognises/);
    // The message names the real vocabulary rather than a hardcoded list.
    for (const c of Object.keys(CHANNEL_CONFIG_LABELS)) expect(ran?.detail).toContain(c);
  });

  it('reports every violation, not just the first', () => {
    const { ran } = caCheck(campaign({ channel: 'RCS' }, { channel: 'SMS', fallbackChannel: 'RCS' }));
    expect(ran?.detail).toMatch(/2 of 3 channel use\(s\) are NOT available/);
  });

  it('a channel violation fails the run even when every other check passes', () => {
    const { report } = caCheck(campaign({ channel: 'RCS' }));
    const others = report.checks.filter((c) => c.id !== 'channel-availability');
    expect(others.length).toBeGreaterThan(0);
    expect(others.every((c) => c.status === 'pass')).toBe(true);
    expect(report.outcome).toBe('failed');
  });
});

describe('channel availability — unusable configuration is not a pass', () => {
  const cases: { label: string; config: unknown; matches: RegExp }[] = [
    { label: 'absent', config: OMIT, matches: /missing or is not a list/ },
    { label: 'not a list', config: { SMS: true }, matches: /missing or is not a list/ },
    { label: 'empty list', config: [], matches: /list is empty/ },
    { label: 'entry not an object', config: ['SMS'], matches: /entry 0 .* is not an object/ },
    { label: 'no channel name', config: [{ available: true }], matches: /no readable "channel" name/ },
    { label: 'blank channel name', config: [{ channel: '  ', available: true }], matches: /no readable "channel" name/ },
    {
      label: 'non-boolean flag',
      config: [{ channel: 'SMS', available: 'yes' }],
      matches: /non-boolean "available" flag .* cannot be interpreted reliably/,
    },
  ];

  for (const { label, config, matches } of cases) {
    it(`records not-run for configuration that is ${label}`, () => {
      // Even with an RCS send present — an unusable list must not produce a
      // pass OR a fail, because nothing could be determined.
      const { report, ran, skipped, registry } = caCheck(campaign({ channel: 'RCS' }), config);
      expect(ran).toBeUndefined();
      expect(skipped?.status).toBe('not-run');
      expect(skipped?.hardConstraint).toBe(true);
      expect(skipped?.unverifiedReason).toMatch(matches);
      expect(skipped?.unverifiedReason).toMatch(/Skipped rather than assumed satisfied/);
      expect(registry.status).toBe('not-run');
      expect(report.unverifiedHardConstraints).toContain('channel-availability');
      expect(report.outcome).toBe('incomplete');
    });
  }

  it('availabilityConfigProblem returns null only for a usable list', () => {
    expect(availabilityConfigProblem(AVAILABLE)).toBeNull();
    expect(availabilityConfigProblem([{ channel: 'SMS', available: false }])).toBeNull(); // usable, just restrictive
  });
});

describe('the planner still selects available channels', () => {
  it('produces a campaign that passes the check, using the real context', () => {
    const bank = bankContext();
    dcResetIdCounters();
    const result = plan(readJson('scenarios/auth-txn-to-emi.json'), bank);

    // Every channel the planner chose is one the issuer marks available.
    const findings = assessChannels(result.graph, bank.channels.available);
    expect(findings.length).toBeGreaterThan(0);
    expect(findings.every((f) => f.verdict === 'available')).toBe(true);
    expect(findings.some((f) => f.channel === 'RCS')).toBe(false);

    const report = validateCampaignGraph(result.graph, result.routingIntent, {
      quietHours: bank.hardConstraints.quietHours,
      availableChannels: bank.channels.available,
    });
    expect(report.hardConstraints.find((c) => c.id === 'channel-availability')?.status).toBe('pass');
    // Still 'incomplete' overall: four constraints have no check yet.
    expect(report.unverifiedHardConstraints).not.toContain('channel-availability');
    expect(report.outcome).toBe('incomplete');
  });
});
