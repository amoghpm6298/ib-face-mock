// Regression tests for design-time quiet-hours handling.
//
// The two things that must not happen:
//
//  1. Claiming compliance for a send whose time is not knowable. Every Send
//     carries absTime: '11:00' from dcDefaultConfig even when timing is
//     'Relative' and the field is unused — so a check that read absTime
//     without gating on timing would manufacture a false pass on the exact
//     campaign the prototype generates.
//  2. Letting an unverifiable HARD constraint come back as 'pre-validated'.
//     That is the same class of defect as the message-cap trace note: a
//     statement that reads as compliance when the truth is "we cannot tell".
//
// Timing semantics are taken from the app, not invented: 'Absolute' stores
// absTime from an <input type="time"> (a time of day, no date) and 'Relative'
// stores a delay from an anchor event (NodeForms.tsx).
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { plan } from './planner';
import { validateCampaignGraph } from './validate';
import { assessSendTimes, isInsideWindow, parseTimeOfDay } from './quietHours';
import { dcResetIdCounters } from '../src/reducer/idGen';
import { dcDefaultConfig } from '../src/reducer/defaultConfig';
import type { DripGraph, DripNode, DripEdge } from '../src/data/graphTypes';
import type { DcNodeType } from '../src/data/nodeMeta';

const here = dirname(fileURLToPath(import.meta.url));
const readJson = (p: string) => JSON.parse(readFileSync(resolve(here, p), 'utf8'));

/** The prototype's INVENTED mock window. Not a verified issuer policy. */
const WINDOW = { from: '21:00', to: '09:00' };
const limits = (quietHours?: { from: string; to: string }) => ({
  maxMessagesPerCustomerPerCampaign: 4,
  ...(quietHours ? { quietHours } : {}),
});

const node = (id: string, type: DcNodeType, config: Record<string, unknown> = {}): DripNode => ({
  id,
  type,
  label: id,
  meta: '',
  autoGenerated: false,
  _config: config,
});
const edge = (id: string, from: string, to: string | null): DripEdge => ({
  id,
  from,
  to,
  branchLabel: '',
  autoGenerated: false,
});

/**
 * One Send, built on top of the APP's own default Send config so the test
 * carries every field a real Send carries — including absTime: '11:00',
 * which is exactly the stale value that must not be trusted on a relative
 * send.
 */
function graphWithSend(sendConfig: Record<string, unknown>): DripGraph {
  return {
    rootId: 'e1',
    nodes: {
      e1: node('e1', 'ENTRY_EVENT', { eventCategory: 'Transaction Events', eventType: 'Transaction' }),
      // Built on the app's real default config, then completed with a real
      // template so dcAddFormValid passes — otherwise node-config fails and
      // the outcome is 'failed' for reasons unrelated to quiet hours.
      s1: node('s1', 'SEND', {
        ...(dcDefaultConfig('SEND', null) as Record<string, unknown>),
        channel: 'SMS',
        account: 'IBL-Karix-Txns',
        templateId: 'CT-3301',
        ...sendConfig,
      }),
      x1: node('x1', 'EXIT', { reason: 'done' }),
    },
    edges: [edge('a', 'e1', 's1'), edge('b', 's1', 'x1')],
  };
}

const quietCheck = (graph: DripGraph, window?: { from: string; to: string }) => {
  const report = validateCampaignGraph(graph, undefined, limits(window));
  return {
    report,
    ran: report.checks.find((c) => c.id === 'quiet-hours'),
    skipped: report.unverified.find((c) => c.id === 'quiet-hours'),
  };
};

describe('quiet hours — window arithmetic', () => {
  it('treats the window as [from, to) and handles the midnight wrap', () => {
    const inside = (t: string) => isInsideWindow(parseTimeOfDay(t)!, WINDOW);
    expect(inside('23:30')).toBe(true); // after from, before midnight
    expect(inside('02:00')).toBe(true); // after midnight, before to
    expect(inside('21:00')).toBe(true); // start is inclusive
    expect(inside('08:59')).toBe(true);
    expect(inside('09:00')).toBe(false); // end is exclusive — quiet UNTIL 9am
    expect(inside('11:00')).toBe(false);
    expect(inside('20:59')).toBe(false);
  });

  it('handles a same-day window too, not just the wrapping case', () => {
    const lunch = { from: '12:00', to: '14:00' };
    expect(isInsideWindow(parseTimeOfDay('13:00')!, lunch)).toBe(true);
    expect(isInsideWindow(parseTimeOfDay('14:00')!, lunch)).toBe(false);
    expect(isInsideWindow(parseTimeOfDay('09:00')!, lunch)).toBe(false);
  });

  it('refuses to answer for an unusable window rather than guessing', () => {
    expect(isInsideWindow(600, { from: 'tonight', to: '09:00' })).toBeNull();
    expect(parseTimeOfDay('24:00')).toBeNull();
    expect(parseTimeOfDay('9:00')).toBeNull(); // app stores zero-padded HH:MM
    expect(parseTimeOfDay(undefined)).toBeNull();
  });
});

describe('quiet hours — a send whose time is KNOWN', () => {
  it('fails a send absolutely timed inside the window', () => {
    const { report, ran } = quietCheck(graphWithSend({ timing: 'Absolute', absTime: '23:30' }), WINDOW);
    expect(ran?.status).toBe('fail');
    expect(ran?.hardConstraint).toBe(true);
    expect(ran?.detail).toMatch(/1 of 1 Send\(s\) fall INSIDE/);
    expect(ran?.detail).toMatch(/s1 "s1" at 23:30/);
    expect(report.outcome).toBe('failed');
  });

  it('passes a send absolutely timed outside the window', () => {
    const { report, ran } = quietCheck(graphWithSend({ timing: 'Absolute', absTime: '11:00' }), WINDOW);
    expect(ran?.status).toBe('pass');
    expect(ran?.detail).toMatch(/all 1 Send\(s\) are absolutely timed and fall outside/);

    // Quiet hours itself is verified and compliant, and is therefore not
    // among the unverified. The run is still 'incomplete' overall because
    // other hard constraints have no check yet — that is the registry
    // working, not a quiet-hours failure.
    expect(report.hardConstraints.find((c) => c.id === 'quiet-hours')?.status).toBe('pass');
    expect(report.unverifiedHardConstraints).not.toContain('quiet-hours');
    expect(report.outcome).toBe('incomplete');
  });

  it('does not claim a pass guarantees runtime enforcement', () => {
    // Rule: design-time validation is not runtime enforcement. A pass has to
    // say so, or it reads as a guarantee the prototype cannot give.
    const { ran } = quietCheck(graphWithSend({ timing: 'Absolute', absTime: '11:00' }), WINDOW);
    expect(ran?.detail).toMatch(/Design-time only/);
    expect(ran?.detail).toMatch(/Drip Campaign runtime/);
  });

  it('a known violation outranks an undetermined sibling', () => {
    const g = graphWithSend({ timing: 'Absolute', absTime: '03:00' });
    g.nodes.s2 = node('s2', 'SEND', {
      ...(g.nodes.s1._config as Record<string, unknown>),
      timing: 'Relative',
      relativeAnchor: 'Entry',
    });
    g.edges = [edge('a', 'e1', 's1'), edge('b', 's1', 's2'), edge('c', 's2', 'x1')];

    const { report, ran } = quietCheck(g, WINDOW);
    expect(ran?.status).toBe('fail'); // established beats unknown
    expect(ran?.detail).toMatch(/1 further Send\(s\) could not be determined/);
    expect(report.outcome).toBe('failed');
  });
});

describe('quiet hours — a send whose time CANNOT be established', () => {
  it('records not-run with a specific reason, and never a pass', () => {
    const { report, ran, skipped } = quietCheck(
      graphWithSend({ timing: 'Relative', relativeAnchor: 'Entry', relativeDuration: 2, relativeUnit: 'hours' }),
      WINDOW,
    );
    expect(ran).toBeUndefined(); // it did not run, so it is not among the ran checks
    expect(skipped?.status).toBe('not-run');
    expect(skipped?.hardConstraint).toBe(true);
    expect(skipped?.unverifiedReason).toMatch(/fires 2 hours after Entry/);
    expect(skipped?.unverifiedReason).toMatch(/cannot be established either way — not that it is satisfied/);
    expect(report.outcome).toBe('incomplete');
  });

  it('ignores the stale absTime that dcDefaultConfig puts on every Send', () => {
    // The trap: a relative Send still carries absTime '11:00' from the app's
    // own default config. 11:00 is outside quiet hours, so a check that read
    // it blindly would report a confident, wrong PASS.
    const relative = graphWithSend({ timing: 'Relative', relativeAnchor: 'Previous Step' });
    expect((relative.nodes.s1._config as Record<string, unknown>).absTime).toBe('11:00');
    expect(isInsideWindow(parseTimeOfDay('11:00')!, WINDOW)).toBe(false); // would have "passed"

    const findings = assessSendTimes(relative, WINDOW);
    expect(findings).toHaveLength(1);
    expect(findings[0].verdict).toBe('undetermined');
  });

  it('treats an absolute send with an unusable absTime as undetermined, not compliant', () => {
    const { report, skipped } = quietCheck(graphWithSend({ timing: 'Absolute', absTime: '' }), WINDOW);
    expect(skipped?.unverifiedReason).toMatch(/not a usable time of day/);
    expect(report.outcome).toBe('incomplete');
  });

  it('skips rather than invents a window when the issuer supplies none', () => {
    // Ownership rule: the agent does not define quiet hours.
    const { report, skipped } = quietCheck(graphWithSend({ timing: 'Absolute', absTime: '23:30' }));
    expect(skipped?.status).toBe('not-run');
    expect(skipped?.unverifiedReason).toMatch(/does not define one/);
    expect(skipped?.unverifiedReason).toMatch(/issuer configuration/);
    expect(report.outcome).toBe('incomplete');
  });
});

describe('an unverifiable hard constraint is never silently passed', () => {
  it('downgrades the outcome to incomplete even when every check that ran passed', () => {
    const { report } = quietCheck(graphWithSend({ timing: 'Relative', relativeAnchor: 'Entry' }), WINDOW);

    // This is the precise situation that used to produce 'pre-validated'.
    expect(report.checks.length).toBeGreaterThan(0);
    expect(report.checks.every((c) => c.status === 'pass')).toBe(true);
    expect(report.outcome).toBe('incomplete');
    expect(report.unverifiedHardConstraints).toContain('quiet-hours');
  });

  it('counts a skipped message cap as an unverified hard constraint too', () => {
    const report = validateCampaignGraph(graphWithSend({ timing: 'Absolute', absTime: '11:00' }));
    expect(report.unverifiedHardConstraints).toEqual(expect.arrayContaining(['message-cap', 'quiet-hours']));
    expect(report.outcome).toBe('incomplete');
  });

  it('a real failure still outranks incompleteness', () => {
    // Over the cap AND quiet hours unverifiable: 'failed' must win, so a
    // violation is never softened into "we could not tell".
    const g = graphWithSend({ timing: 'Relative', relativeAnchor: 'Entry' });
    const report = validateCampaignGraph(g, undefined, {
      maxMessagesPerCustomerPerCampaign: 0,
      quietHours: WINDOW,
    });
    expect(report.checks.find((c) => c.id === 'message-cap')?.status).toBe('fail');
    expect(report.unverifiedHardConstraints).toContain('quiet-hours');
    expect(report.outcome).toBe('failed');
  });

  it('the real generated campaign is incomplete, not pre-validated', () => {
    // End-to-end on the actual scenario: both Sends are relatively timed,
    // so quiet-hours compliance genuinely cannot be established.
    const bank = readJson('context/bank-context.json');
    dcResetIdCounters();
    const result = plan(readJson('scenarios/auth-txn-to-emi.json'), bank);
    const report = validateCampaignGraph(result.graph, result.routingIntent, {
      quietHours: bank.hardConstraints.quietHours,
    });

    expect(report.checks.every((c) => c.status === 'pass')).toBe(true);
    expect(report.unverifiedHardConstraints).toContain('quiet-hours');
    expect(report.outcome).toBe('incomplete');

    // The planner states the cause, so the outcome is explained not just reported.
    expect(result.trace.some((e) => /not knowable at design time/.test(e.message))).toBe(true);
  });
});
