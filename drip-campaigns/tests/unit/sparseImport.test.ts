// An imported file is not guaranteed to be complete. The designer leaves out
// what it does not know, so every node type has to survive arriving with no
// config at all, or with only some of its keys — and then be fillable.
//
// "Fillable" has a precondition these tests cover: nothing may THROW while
// reading an incomplete node, because the throw would take down the very
// canvas and drawer the manager needs in order to complete it.
import { describe, expect, it } from 'vitest';
import type { DcNodeType } from '../../src/data/nodeMeta';
import { DC_NODE_META } from '../../src/data/nodeMeta';
import { dcRecomputeLabelMeta } from '../../src/reducer/labelMeta';
import { dcAddFormValid } from '../../src/reducer/defaultConfig';
import { ingestCampaignJson, parseCampaignFile } from '../../src/data/ingestCampaign';

const ALL_TYPES = Object.keys(DC_NODE_META) as DcNodeType[];

describe('every node type reads safely with nothing filled in', () => {
  it.each(ALL_TYPES)('%s survives a null config', (t) => {
    expect(() => dcRecomputeLabelMeta(t, null, null)).not.toThrow();
    expect(() => dcAddFormValid(t, null)).not.toThrow();
  });

  it.each(ALL_TYPES)('%s survives an empty config', (t) => {
    expect(() => dcRecomputeLabelMeta(t, {}, null)).not.toThrow();
    expect(() => dcAddFormValid(t, {})).not.toThrow();
  });

  it.each(ALL_TYPES)('%s never renders the word undefined', (t) => {
    for (const cfg of [null, {}]) {
      const { label, meta } = dcRecomputeLabelMeta(t, cfg, null);
      expect(`${label} ${meta}`.toLowerCase(), `${t} with ${JSON.stringify(cfg)}`).not.toContain('undefined');
      expect(`${label} ${meta}`.toLowerCase()).not.toContain('null');
    }
  });

  it.each(ALL_TYPES)('%s still names itself, so no card is blank', (t) => {
    expect(dcRecomputeLabelMeta(t, {}, null).label.trim().length).toBeGreaterThan(0);
  });

  it('an incomplete node is simply not valid yet, rather than an error', () => {
    expect(dcAddFormValid('SEND', null)).toBe(false);
    expect(dcAddFormValid('RANDOM_SPLIT', {})).toBe(false);
    expect(dcAddFormValid('DECISION_SPLIT', {})).toBe(false);
  });

  it('a half-filled duration says only what it knows', () => {
    expect(dcRecomputeLabelMeta('PAUSE', {}, null).label).toBe('Wait');
    expect(dcRecomputeLabelMeta('PAUSE', { duration: 3 }, null).label).toBe('Wait');
    expect(dcRecomputeLabelMeta('PAUSE', { duration: 3, unit: 'days' }, null).label).toBe('Wait 3 days');
    // An optional meta line is better absent than half-written.
    expect(dcRecomputeLabelMeta('WAIT_UNTIL', {}, null).meta).toBe('');
  });

  it('an experiment with no variants reads as one, with no dangling dash', () => {
    const { label, meta } = dcRecomputeLabelMeta('RANDOM_SPLIT', {}, null);
    expect(label).toBe('Experiment');
    expect(meta).toBe('0 variants');
    expect(meta).not.toMatch(/—\s*$/);
  });
});

describe('ingest names the steps a file did not name', () => {
  function graphOf(nodes: Record<string, unknown>) {
    return { campaign: { name: 'x', root: { rootId: 'n1', nodes, edges: [] } } };
  }
  const node = (type: string, extra: Record<string, unknown> = {}) => ({ id: 'n1', type, meta: '', _config: {}, autoGenerated: false, ...extra });

  it('derives a label for a node that arrived without one', () => {
    const r = ingestCampaignJson(graphOf({ n1: node('RANDOM_SPLIT', { _config: { branches: [{ id: 'b', label: 'A', pct: 100 }] } }) }), 'DRIP-1');
    if (!r.ok) throw new Error('rejected');
    expect(r.campaign.root!.nodes.n1.label).toBe('Experiment');
  });

  it("never overwrites a label the file did supply — that is the designer's wording", () => {
    const r = ingestCampaignJson(graphOf({ n1: node('RANDOM_SPLIT', { label: 'Dormancy explanation test', _config: { name: 'ignored', branches: [] } }) }), 'DRIP-2');
    if (!r.ok) throw new Error('rejected');
    expect(r.campaign.root!.nodes.n1.label).toBe('Dormancy explanation test');
  });

  it('a node with a null config still gets a readable name', () => {
    const r = ingestCampaignJson(graphOf({ n1: node('GOAL_EXIT', { label: '', _config: null }) }), 'DRIP-3');
    if (!r.ok) throw new Error('rejected');
    expect(r.campaign.root!.nodes.n1.label).toBe('Goal reached');
  });
});

describe('the imported file is kept, so it can be read back and handed on', () => {
  const FILE = JSON.stringify({ campaign: { name: 'Keep me', root: { rootId: 'n1', nodes: {}, edges: [] } }, claim: 'not saved or activated' });

  it('is stored verbatim, including the blocks this app does not read', () => {
    const r = parseCampaignFile(FILE, 'DRIP-10');
    if (!r.ok) throw new Error('rejected');
    expect(r.campaign.importedJson).toBe(FILE);
    expect(r.campaign.importedJson).toContain('"claim"');
    expect(JSON.parse(r.campaign.importedJson!)).toEqual(JSON.parse(FILE));
  });

  it('records when it arrived', () => {
    const r = parseCampaignFile(FILE, 'DRIP-11');
    if (!r.ok) throw new Error('rejected');
    expect(Number.isNaN(Date.parse(r.campaign.importedAt!))).toBe(false);
  });

  it('those wrapper blocks are still not merged onto the campaign itself', () => {
    const r = parseCampaignFile(FILE, 'DRIP-12');
    if (!r.ok) throw new Error('rejected');
    expect((r.campaign as Record<string, unknown>).claim).toBeUndefined();
  });

  it('a campaign built from scratch carries no imported file', () => {
    const r = ingestCampaignJson({ root: { rootId: 'n1', nodes: {}, edges: [] } }, 'DRIP-13');
    if (!r.ok) throw new Error('rejected');
    // ingest always has SOMETHING handed to it, so it records that; the real
    // "no file" case is a campaign the builder made, which never goes
    // through ingest at all.
    expect(typeof r.campaign.importedJson).toBe('string');
  });
});
