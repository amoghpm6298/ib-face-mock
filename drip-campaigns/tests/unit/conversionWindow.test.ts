// Commit 2 — what counts as a conversion, and for how long.
//
// Conversion left the canvas, so the two things a node used to imply have to
// be said somewhere: how long after entering it still counts, and whether
// converting takes the customer out of the journey.
import { describe, expect, it } from 'vitest';
import type { DripGoal, DripGraph } from '../../src/data/graphTypes';
import { dcJourneyLengthDays, dcSuggestConversionWindow, dcConversionSentence, dcWindowNote } from '../../src/data/conversionWindow';
import { dcValidateSetup } from '../../src/reducer/campaignReducer';
import { DRIP_CAMPAIGNS } from '../../src/data/seedCampaigns';

const node = (id: string, type: string, cfg: unknown = null) => ({ id, type, label: id, meta: '', autoGenerated: false, _config: cfg }) as never;
const chain = (steps: { type: string; cfg?: unknown }[]): DripGraph => ({
  rootId: 'n0',
  nodes: Object.fromEntries(steps.map((s, i) => [`n${i}`, node(`n${i}`, s.type, s.cfg ?? null)])),
  edges: steps.slice(1).map((_, i) => ({ id: `e${i}`, from: `n${i}`, to: `n${i + 1}`, branchLabel: '', autoGenerated: false, port: 'next' })),
});

describe('how long the journey runs', () => {
  it('adds up the waits along it — sends take no time of their own', () => {
    const g = chain([
      { type: 'ENTRY_EVENT' },
      { type: 'SEND', cfg: { name: 'a' } },
      { type: 'PAUSE', cfg: { duration: 3, unit: 'days' } },
      { type: 'SEND', cfg: { name: 'b' } },
      { type: 'PAUSE', cfg: { duration: 4, unit: 'days' } },
    ]);
    expect(dcJourneyLengthDays(g)).toBe(7);
  });

  it('counts a Wait for Event by its timeout, and hours as part of a day', () => {
    const g = chain([
      { type: 'ENTRY_EVENT' },
      { type: 'WAIT_UNTIL', cfg: { eventType: 'x', duration: 2, unit: 'days' } },
      { type: 'PAUSE', cfg: { duration: 12, unit: 'hours' } },
    ]);
    expect(dcJourneyLengthDays(g)).toBe(2.5);
  });

  it('takes the longest branch, not the sum of all of them', () => {
    const g: DripGraph = {
      rootId: 'a',
      nodes: {
        a: node('a', 'SPLIT'),
        short: node('short', 'PAUSE', { duration: 1, unit: 'days' }),
        long: node('long', 'PAUSE', { duration: 9, unit: 'days' }),
      },
      edges: [
        { id: 'e1', from: 'a', to: 'short', branchLabel: 'Yes', autoGenerated: false, port: 'yes' },
        { id: 'e2', from: 'a', to: 'long', branchLabel: 'No', autoGenerated: false, port: 'no' },
      ],
    };
    expect(dcJourneyLengthDays(g)).toBe(9);
  });

  it('does not hang on a graph that loops back on itself', () => {
    const g: DripGraph = {
      rootId: 'a',
      nodes: { a: node('a', 'PAUSE', { duration: 1, unit: 'days' }), b: node('b', 'PAUSE', { duration: 1, unit: 'days' }) },
      edges: [
        { id: 'e1', from: 'a', to: 'b', branchLabel: '', autoGenerated: false, port: 'next' },
        { id: 'e2', from: 'b', to: 'a', branchLabel: '', autoGenerated: false, port: 'next' },
      ],
    };
    expect(dcJourneyLengthDays(g)).toBe(2);
  });

  it('an empty journey still suggests the buffer, not zero', () => {
    // A goal can be set before any step exists. Three days is the buffer on
    // its own — a real number the author can see and change.
    expect(dcSuggestConversionWindow(null)).toEqual({ duration: 3, unit: 'days' });
  });

  it('suggests the journey plus a buffer', () => {
    const g = chain([{ type: 'ENTRY_EVENT' }, { type: 'PAUSE', cfg: { duration: 10, unit: 'days' } }]);
    expect(dcSuggestConversionWindow(g)).toEqual({ duration: 13, unit: 'days' });
  });
});

describe('saying what will be counted', () => {
  const goal: DripGoal = { eventCategory: 'Card Events', eventType: 'Virtual card activated', conditions: [], conversionWindow: { duration: 13, unit: 'days' } };

  it('names the event, the window, and that both groups are measured alike', () => {
    expect(dcConversionSentence(goal)).toBe(
      'A conversion is someone doing Virtual card activated after they enter this campaign. It counts if it happens within 13 days of them entering. The held-back group is measured the same way.',
    );
  });

  it('drops the window for the Goal step, where the field below already shows it', () => {
    expect(dcConversionSentence(goal, { withWindow: false })).toBe(
      'A conversion is someone doing Virtual card activated after they enter this campaign.',
    );
  });

  it('says so plainly when no window is set, rather than implying one', () => {
    expect(dcConversionSentence({ ...goal, conversionWindow: undefined })).toContain('No time limit is set');
  });

  it('says nothing at all with no goal', () => {
    expect(dcConversionSentence(null)).toBe('');
    expect(dcConversionSentence({ eventType: '' })).toBe('');
  });
});

describe('the submit gate', () => {
  const base = { name: 'C', issuer: 'IndusInd Bank (IBL)', applyToAllPrograms: true, programs: [], controlPct: 10 };
  const msgs = (goal: DripGoal | null) => dcValidateSetup({ ...base, goal } as never).map((i) => i.message).join(' | ');
  const goal: DripGoal = { eventCategory: 'Card Events', eventType: 'Virtual card activated', conditions: [] };

  it('refuses a goal with no window — it would count nothing', () => {
    expect(msgs(goal)).toMatch(/Set a conversion window/);
  });

  it('refuses a window of zero or less', () => {
    expect(msgs({ ...goal, conversionWindow: { duration: 0, unit: 'days' } })).toMatch(/Set a conversion window/);
    expect(msgs({ ...goal, conversionWindow: { duration: -3, unit: 'days' } })).toMatch(/Set a conversion window/);
  });

  it('accepts a real window, and says nothing when there is no goal at all', () => {
    expect(msgs({ ...goal, conversionWindow: { duration: 7, unit: 'days' } })).toBe('');
    expect(msgs(null)).toBe('');
  });
});

describe('the seeds', () => {
  it('every campaign with a goal carries a window and says either way whether it exits on conversion', () => {
    for (const c of DRIP_CAMPAIGNS) {
      if (!c.goal?.eventType) continue;
      expect({ id: c.id, window: Number(c.goal.conversionWindow?.duration) > 0 }).toEqual({ id: c.id, window: true });
      expect({ id: c.id, set: typeof c.goal.exitOnConversion }).toEqual({ id: c.id, set: 'boolean' });
    }
  });

  // A Goal Check is only offered while exit on conversion is off: with it on,
  // an account that converts has already left, so the check could only ever
  // answer No. The seeds have to honour that both ways round.
  it('a Goal Check appears only where the campaign does not exit on conversion', () => {
    for (const c of DRIP_CAMPAIGNS) {
      if (!c.root) continue;
      const hasCheck = Object.values(c.root.nodes).some((n) => n.type === 'GOAL_CHECK');
      if (hasCheck) expect({ id: c.id, exits: c.goal?.exitOnConversion }).toEqual({ id: c.id, exits: false });
    }
  });

  it('each window covers its own journey, which is what the suggestion is for', () => {
    for (const c of DRIP_CAMPAIGNS) {
      if (!c.goal?.eventType || !c.root) continue;
      const journey = dcJourneyLengthDays(c.root);
      expect({ id: c.id, covers: Number(c.goal.conversionWindow!.duration) >= journey }).toEqual({ id: c.id, covers: true });
    }
  });
});

describe('explaining the number', () => {
  const goal = (duration: number, unit = 'days') => ({ conversionWindow: { duration, unit } });

  it('says the window covers the journey, with room after the last message', () => {
    expect(dcWindowNote(goal(13), 10)).toMatch(/runs about 10 days, so that covers it/);
  });

  it('calls out a window SHORTER than the journey — the last message lands after the clock stops', () => {
    const note = dcWindowNote(goal(5), 10);
    expect(note).toMatch(/last message goes out after this window closes/);
    expect(note).toMatch(/would not be counted/);
  });

  it('reads hours against the journey in days, not as days', () => {
    // 12 hours is half a day, so it is short of a 10-day journey.
    expect(dcWindowNote(goal(12, 'hours'), 10)).toMatch(/after this window closes/);
  });

  it('falls back to the reason alone when there is no journey yet', () => {
    expect(dcWindowNote(goal(7), 0)).toMatch(/probably was not nudged by this campaign/);
  });

  it('says the reason when no window is set at all', () => {
    expect(dcWindowNote(null, 10)).toMatch(/keeps the report honest/);
  });
});
