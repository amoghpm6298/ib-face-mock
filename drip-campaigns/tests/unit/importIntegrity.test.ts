// What a file has to be structurally sound enough to import.
//
// Before this, the only structural check was "nodes is an object and edges
// is an array". Everything below came through, became a DRAFT, and opened in
// the builder as a journey the manager could neither read nor repair —
// arrows into steps that were not in the file, or a crash on the first
// missing lookup. None of it is fixable in a drawer, which is why each one
// is a reject rather than an entry in the submit gate's issue list.
import { describe, it, expect } from 'vitest';
import { ingestCampaignJson } from '../../src/data/ingestCampaign';
import { dcValidateCampaign } from '../../src/reducer/campaignReducer';

const send = (id: string) => ({ id, type: 'SEND', label: 'Welcome', meta: '', autoGenerated: false, _config: { name: 'Welcome' } });
const graph = (over: Record<string, unknown> = {}) => ({
  name: 'x',
  root: { rootId: 'n1', nodes: { n1: send('n1') }, edges: [], ...over },
});
const err = (raw: unknown) => {
  const r = ingestCampaignJson(raw, 'DRIP-X');
  return r.ok ? null : r.error;
};

describe('a file has to hold a journey that can be drawn', () => {
  it('a sound one-step file imports', () => {
    expect(err(graph())).toBe(null);
  });

  it('no steps at all is not a campaign', () => {
    expect(err(graph({ nodes: {} }))).toBe('This file has no steps in it.');
  });

  it('a start step that is not in the file is rejected, naming it', () => {
    expect(err(graph({ rootId: 'n9' }))).toContain('"n9"');
  });

  it('no start step at all is rejected', () => {
    expect(err(graph({ rootId: null }))).toBe('This file does not say which step starts the journey.');
  });

  it('a step filed under a key that disagrees with its own id is rejected', () => {
    // The canvas resolves handles, incoming counts and metrics by node.id
    // while edges and layout resolve by key — the two disagreeing is a
    // journey that renders with its arrows attached to nothing.
    expect(err(graph({ nodes: { n1: send('somethingElse') } }))).toContain('filed under a different id');
  });

  it('a kind of step this builder does not have is rejected, naming it', () => {
    expect(err(graph({ nodes: { n1: { ...send('n1'), type: 'TELEPATHY' } } }))).toContain('"TELEPATHY"');
  });

  it('an edge from a step that is not in the file is rejected', () => {
    const edges = [{ id: 'e1', from: 'ghost', to: 'n1', branchLabel: '', autoGenerated: false }];
    expect(err(graph({ edges }))).toContain('comes from a step that is not in the file');
  });

  it('an edge to a step that is not in the file is rejected', () => {
    const edges = [{ id: 'e1', from: 'n1', to: 'ghost', branchLabel: '', autoGenerated: false }];
    expect(err(graph({ edges }))).toContain('goes to a step that is not in the file');
  });

  it('an edge to nothing is fine — that is an open slot, not a break', () => {
    const edges = [{ id: 'e1', from: 'n1', to: null, branchLabel: '', autoGenerated: false }];
    expect(err(graph({ edges }))).toBe(null);
  });

  it('two edges sharing one id is rejected, because branches reconcile by it', () => {
    const edges = [
      { id: 'e1', from: 'n1', to: null, branchLabel: 'Yes', autoGenerated: false },
      { id: 'e1', from: 'n1', to: null, branchLabel: 'No', autoGenerated: false },
    ];
    expect(err(graph({ edges }))).toContain('share one id');
  });

  it('an edge with no id is rejected', () => {
    const edges = [{ from: 'n1', to: null, branchLabel: '', autoGenerated: false }];
    expect(err(graph({ edges }))).toContain('no id');
  });
});

describe('integrity is not the submit gate', () => {
  // The distinction that decides what belongs here: an import lands as a
  // DRAFT and opens straight in the builder, where dcValidateCampaign is
  // already on screen listing what is unfinished. Refusing a file for being
  // unfinished would refuse the normal case.
  const unfinished = graph({
    nodes: { n1: send('n1'), n2: { id: 'n2', type: 'SEND', label: 'No config', meta: '', autoGenerated: false, _config: {} } },
    edges: [{ id: 'e1', from: 'n1', to: 'n2', branchLabel: '', autoGenerated: false }],
  });

  it('a file whose steps are incomplete still imports', () => {
    expect(err(unfinished)).toBe(null);
  });

  it('and the submit gate is the thing that reports it, once it is open', () => {
    const r = ingestCampaignJson(unfinished, 'DRIP-Y');
    if (!r.ok) throw new Error(r.error);
    const issues = dcValidateCampaign(r.campaign.root!, r.campaign.goal);
    expect(issues.length).toBeGreaterThan(0);
  });
});
