// No undefined on the canvas. An imported Send can arrive with no timing
// filed; the card simply has no timing line, and nothing is invented.
import { describe, expect, it } from 'vitest';
import type { DripGraph } from '../../src/data/graphTypes';
import { graphToFlowElements } from '../../src/canvas/toFlowElements';

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function sendGraph(config: any): DripGraph {
  return {
    rootId: 's1',
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    nodes: { s1: { id: 's1', type: 'SEND', label: 'A send', meta: '', _config: config, autoGenerated: false } as any },
    edges: [],
  };
}
function timingOf(config: unknown): unknown {
  const els = graphToFlowElements(sendGraph(config), { editable: false });
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  return (els.nodes.find((n) => n.id === 's1')?.data as any).timingLabel;
}

describe('a Send card’s timing line', () => {
  it('a Send that filed 11:00 still shows 11:00', () => {
    expect(timingOf({ channel: 'WHATSAPP', timing: 'Absolute', absTime: '11:00' })).toBe('11:00 AM');
  });

  it('a Send with no timing at all renders no timing line, not "undefined undefined"', () => {
    const label = timingOf({ name: 'Low ticket', channel: 'SMS', account: '', templateId: '' });
    expect(label).toBe('');
    expect(String(label)).not.toContain('undefined');
  });

  it.each([
    ['a blank duration', { relativeDuration: '', relativeUnit: 'days' }],
    ['a null duration', { relativeDuration: null, relativeUnit: 'days' }],
    ['a non-numeric duration', { relativeDuration: 'soon', relativeUnit: 'days' }],
    ['a duration with no unit', { relativeDuration: 3 }],
  ])('%s says nothing rather than something made up', (_name, cfg) => {
    const label = timingOf({ channel: 'SMS', ...cfg });
    expect(label).toBe('');
    expect(String(label)).not.toContain('undefined');
  });

  it('a real relative timing is untouched', () => {
    expect(timingOf({ channel: 'SMS', relativeDuration: 3, relativeUnit: 'days' })).toBe('3 days after previous step');
    expect(timingOf({ channel: 'SMS', relativeDuration: 0, relativeUnit: 'days' })).toBe('Immediately after previous step');
  });
});
