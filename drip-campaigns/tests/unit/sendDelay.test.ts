// M3 — a delay no longer lives inside a Send.
//
// It used to: "Relative" timing held a duration and a unit, which is a wait
// that nothing could see. It was not a step on the canvas, analytics did not
// model it, and — the reason it matters after C1 — it did not listen for the
// goal, so a customer who converted during those three days was messaged
// anyway. That is C1's defect wearing a different hat.
import { describe, expect, it } from 'vitest';
import type { DripGraph } from '../../src/data/graphTypes';
import { dcSendTimingOf, dcSendTimingLabel } from '../../src/data/sendTiming';
import { dcDefaultConfig } from '../../src/reducer/defaultConfig';
import { dcValidateCampaign } from '../../src/reducer/campaignReducer';
import { DRIP_CAMPAIGNS } from '../../src/data/seedCampaigns';

describe('when a send goes out', () => {
  it('at a set time of day', () => {
    expect(dcSendTimingOf({ timing: 'Absolute', absTime: '11:00' })).toEqual({ kind: 'at', time: '11:00' });
    expect(dcSendTimingLabel({ kind: 'at', time: '11:00' })).toBe('11:00 AM');
    expect(dcSendTimingLabel({ kind: 'at', time: '00:30' })).toBe('12:30 AM');
    expect(dcSendTimingLabel({ kind: 'at', time: '13:05' })).toBe('1:05 PM');
  });

  it('or as soon as the customer reaches the step', () => {
    expect(dcSendTimingOf({ timing: 'Immediate' })).toEqual({ kind: 'immediate' });
  });

  it('reads a legacy zero-delay "Relative" as immediate, which is what it always meant', () => {
    expect(dcSendTimingOf({ timing: 'Relative', relativeDuration: 0, relativeUnit: 'days' })).toEqual({ kind: 'immediate' });
    expect(dcSendTimingOf({ timing: 'Relative' })).toEqual({ kind: 'immediate' });
  });

  it('keeps a legacy positive delay readable rather than dropping it silently', () => {
    // Hiding it would leave the send going out three days later than
    // anything on screen claims.
    expect(dcSendTimingOf({ timing: 'Relative', relativeDuration: 3, relativeUnit: 'days' })).toEqual({ kind: 'legacyDelay', duration: 3, unit: 'days' });
  });

  it('says nothing when nothing is filed, rather than inventing a time', () => {
    expect(dcSendTimingOf({})).toEqual({ kind: 'unset' });
    expect(dcSendTimingOf({ timing: 'Absolute' })).toEqual({ kind: 'unset' });
    expect(dcSendTimingLabel({ kind: 'unset' })).toBe('');
  });
});

describe('a new Send carries no delay fields at all', () => {
  it('because there is no longer anywhere to put one', () => {
    const cfg = dcDefaultConfig('SEND') as Record<string, unknown>;
    expect(cfg.relativeDuration).toBeUndefined();
    expect(cfg.relativeUnit).toBeUndefined();
    // relativeAnchor was stored and no form ever offered it, while the one
    // label that existed said "after previous step" regardless.
    expect(cfg.relativeAnchor).toBeUndefined();
    expect(cfg.timing).toBe('Absolute');
  });
});

describe('a campaign saved with a delay inside a send', () => {
  const graph = (): DripGraph => ({
    rootId: 'n1',
    nodes: {
      n1: { id: 'n1', type: 'ENTRY_EVENT', label: 'Pageload', meta: '', autoGenerated: false, _config: { eventCategory: 'Journey Events', eventType: 'Pageload' } },
      n2: { id: 'n2', type: 'SEND', label: 'Nudge', meta: '', autoGenerated: false, _config: { name: 'Nudge', channel: 'SMS', account: 'IBL-Karix-Txns', templateId: 'CT-3301', timing: 'Relative', relativeDuration: 3, relativeUnit: 'days' } },
      n3: { id: 'n3', type: 'EXIT', label: 'Done', meta: '', autoGenerated: false, _config: { reason: 'Done' } },
    },
    edges: [
      { id: 'e1', from: 'n1', to: 'n2', branchLabel: '', autoGenerated: false, port: 'next' },
      { id: 'e2', from: 'n2', to: 'n3', branchLabel: '', autoGenerated: false, port: 'next' },
    ],
  });

  it('is named by the submit gate, with what to do instead', () => {
    const msgs = dcValidateCampaign(graph(), null).map((i) => i.message).join(' | ');
    expect(msgs).toMatch(/waits inside the send/);
    expect(msgs).toMatch(/Add a Wait step/);
  });

  it('is reported and not migrated, because where the Wait goes is the author\'s call', () => {
    const g = graph();
    dcValidateCampaign(g, null);
    expect((g.nodes.n2._config as { relativeDuration?: number }).relativeDuration).toBe(3);
    expect(Object.values(g.nodes).some((n) => n.type === 'PAUSE')).toBe(false);
  });
});

describe('the seeds carry no delays', () => {
  it('every seeded Send is either at a time of day or immediate', () => {
    const kinds = new Set<string>();
    for (const c of DRIP_CAMPAIGNS) {
      if (!c.root) continue;
      for (const n of Object.values(c.root.nodes)) {
        if (n.type !== 'SEND') continue;
        kinds.add(dcSendTimingOf(n._config).kind);
      }
    }
    expect([...kinds].sort()).toEqual(['at', 'immediate']);
  });
});
