// M7/M8 — what the submit gate refuses about the campaign's own setup, and
// about a campaign whose entry already satisfies its goal.
//
// None of this was checked before: name and issuer were tested in a ternary
// chain inside the Builder's render, and scope, the control group and the
// dates were not tested anywhere. A campaign could be complete, valid and
// addressed to nobody.
import { describe, expect, it } from 'vitest';
import type { DripGoal, DripGraph } from '../../src/data/graphTypes';
import { dcValidateSetup, dcValidateCampaign, type DripCampaignSetup } from '../../src/reducer/campaignReducer';

const OK: DripCampaignSetup = {
  name: 'Activation drip',
  issuer: 'IndusInd Bank (IBL)',
  applyToAllPrograms: true,
  programs: [],
  controlPct: 10,
  startDate: '',
  endDate: '',
};
const msgs = (s: Partial<DripCampaignSetup>) => dcValidateSetup({ ...OK, ...s }).map((i) => i.message).join(' | ');
const future = () => { const d = new Date(); d.setFullYear(d.getFullYear() + 1); return d.toISOString().slice(0, 10); };
const past = () => { const d = new Date(); d.setFullYear(d.getFullYear() - 1); return d.toISOString().slice(0, 10); };

describe('who the campaign is for', () => {
  it('a sound setup raises nothing', () => {
    expect(dcValidateSetup(OK)).toEqual([]);
  });

  it('needs a name', () => {
    expect(msgs({ name: '   ' })).toMatch(/name/);
  });

  it('needs an issuer', () => {
    expect(msgs({ issuer: '' })).toMatch(/issuer/);
  });

  it('refuses an issuer with no programs and the all-programs toggle off — it reaches nobody', () => {
    expect(msgs({ applyToAllPrograms: false, programs: [] })).toMatch(/reach nobody/);
  });

  it('accepts named programs, and accepts all-programs with none named', () => {
    expect(msgs({ applyToAllPrograms: false, programs: ['Program A'] })).toBe('');
    expect(msgs({ applyToAllPrograms: true, programs: [] })).toBe('');
  });

  it('does not complain about programs when there is no issuer yet — one problem at a time', () => {
    const out = msgs({ issuer: '', applyToAllPrograms: false, programs: [] });
    expect(out).toMatch(/issuer/);
    expect(out).not.toMatch(/reach nobody/);
  });
});

describe('the control group', () => {
  it('accepts 0 and 50, the real ends of the range', () => {
    expect(msgs({ controlPct: 0 })).toBe('');
    expect(msgs({ controlPct: 50 })).toBe('');
  });

  it('refuses past 50 and below 0, which the input attributes alone never caught', () => {
    expect(msgs({ controlPct: 80 })).toMatch(/between 0% and 50%/);
    expect(msgs({ controlPct: -5 })).toMatch(/between 0% and 50%/);
  });

  it('refuses an emptied field, which reads as NaN rather than as zero', () => {
    expect(msgs({ controlPct: Number('') || NaN })).toMatch(/whole percentage/);
  });

  it('refuses a fraction of a percent', () => {
    expect(msgs({ controlPct: 10.5 })).toMatch(/whole percentage/);
  });
});

describe('when it runs', () => {
  it('refuses an end before the start', () => {
    expect(msgs({ startDate: future(), endDate: past() })).toMatch(/end date is before the start date/);
  });

  it('refuses an end date that has already passed', () => {
    expect(msgs({ endDate: past() })).toMatch(/already passed/);
  });

  it('accepts a start date in the past, because editing a campaign that already began is ordinary', () => {
    expect(msgs({ startDate: past(), endDate: future() })).toBe('');
  });

  it('accepts no dates at all — that is "starts as soon as it is submitted"', () => {
    expect(msgs({ startDate: '', endDate: '' })).toBe('');
  });
});

describe('a campaign whose entry already achieves its goal', () => {
  const goal: DripGoal = { eventCategory: 'Card Events', eventType: 'Virtual card activated', conditions: [] };
  const entryGraph = (cfg: Record<string, unknown>): DripGraph => ({
    rootId: 'n1',
    nodes: {
      n1: { id: 'n1', type: 'ENTRY_EVENT', label: String(cfg.eventType || 'Entry'), meta: '', autoGenerated: false, _config: cfg },
      n2: { id: 'n2', type: 'EXIT', label: 'Done', meta: '', autoGenerated: false, _config: { reason: 'Done' } },
    },
    edges: [{ id: 'e1', from: 'n1', to: 'n2', branchLabel: '', autoGenerated: false }],
  });
  const campaignMsgs = (cfg: Record<string, unknown>, g: DripGoal | null = goal) =>
    dcValidateCampaign(entryGraph(cfg), g, OK).map((i) => i.message).join(' | ');

  it('is refused — the funnel would read 100% and no message in it caused anything', () => {
    expect(campaignMsgs({ eventCategory: 'Card Events', eventType: 'Virtual card activated' })).toMatch(/already achieved the goal/);
  });

  it('is fine when the entry is a different event', () => {
    expect(campaignMsgs({ eventCategory: 'Card Events', eventType: 'Virtual card issued' })).toBe('');
  });

  it('is fine when the entry is BROADER than the goal — entering is not yet converting', () => {
    // Enter on any transaction, aim for one of at least ₹5,000.
    const bigTxn: DripGoal = {
      eventCategory: 'Transaction Events',
      eventType: 'Transaction',
      conditions: [{ attribute: 'Transaction Amount', operator: 'is at least', value: '5000' }],
    };
    expect(campaignMsgs({ eventCategory: 'Transaction Events', eventType: 'Transaction', conditions: [] }, bigTxn)).toBe('');
  });

  it('is refused when the entry carries the goal\'s own condition too', () => {
    const bigTxn: DripGoal = {
      eventCategory: 'Transaction Events',
      eventType: 'Transaction',
      conditions: [{ attribute: 'Transaction Amount', operator: 'is at least', value: '5000' }],
    };
    const cfg = { eventCategory: 'Transaction Events', eventType: 'Transaction', conditions: bigTxn.conditions };
    expect(campaignMsgs(cfg, bigTxn)).toMatch(/already achieved the goal/);
  });

  it('says nothing when no goal is defined', () => {
    expect(campaignMsgs({ eventCategory: 'Card Events', eventType: 'Virtual card activated' }, null)).toBe('');
  });

  it('says nothing about an audience entry, which cannot be an event', () => {
    const g: DripGraph = {
      rootId: 'n1',
      nodes: {
        n1: { id: 'n1', type: 'ENTRY_SEGMENT', label: 'Audience', meta: '', autoGenerated: false, _config: { cohortDesc: 'Audience', filters: [] } },
        n2: { id: 'n2', type: 'EXIT', label: 'Done', meta: '', autoGenerated: false, _config: { reason: 'Done' } },
      },
      edges: [{ id: 'e1', from: 'n1', to: 'n2', branchLabel: '', autoGenerated: false }],
    };
    expect(dcValidateCampaign(g, goal, OK)).toEqual([]);
  });
});

describe('the gate is one list', () => {
  it('setup problems are reported even when the journey has no entry step yet', () => {
    const empty: DripGraph = { nodes: {}, edges: [], rootId: null };
    const out = dcValidateCampaign(empty, null, { ...OK, name: '' }).map((i) => i.message).join(' | ');
    expect(out).toMatch(/name/);
    expect(out).toMatch(/Add an entry step/);
  });

  it('omitting setup entirely still validates the journey, for callers that only have a graph', () => {
    const empty: DripGraph = { nodes: {}, edges: [], rootId: null };
    expect(dcValidateCampaign(empty, null)).toEqual([{ nodeId: null, message: 'Add an entry step before submitting.' }]);
  });
});
