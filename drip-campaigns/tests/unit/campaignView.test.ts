// What the campaign view puts on the journey: one count per step, a split
// written on the arrows of a step that divides people, and nothing on an
// arrow that does not divide anyone.
import { describe, expect, it } from 'vitest';
import type { DripGraph } from '../../src/data/graphTypes';
import { graphToFlowElements } from '../../src/canvas/toFlowElements';
import { generateDripAnalytics } from '../../src/data/dripAnalytics';
import { DRIP_CAMPAIGNS } from '../../src/data/seedCampaigns';
import { dcPathThroughEdge } from '../../src/list/DripAnalytics';

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function node(id: string, type: string, label: string): any {
  return { id, type, label, meta: '', _config: {}, autoGenerated: false };
}
function edge(id: string, from: string, to: string | null, branchLabel = ''): DripGraph['edges'][number] {
  return { id, from, to, branchLabel, branchId: null, autoGenerated: false };
}

// entry ──► pause ──► split ──┬─ Yes ─► exitA
//                             └─ No ──► exitB
function routingGraph(): DripGraph {
  return {
    rootId: 'n1',
    nodes: {
      n1: node('n1', 'ENTRY_SEGMENT', 'Everyone'),
      n2: node('n2', 'PAUSE', 'Wait 3 days'),
      n3: node('n3', 'SPLIT', 'Activated?'),
      n4: node('n4', 'GOAL_EXIT', 'Reached'),
      n5: node('n5', 'EXIT', 'Exhausted'),
    },
    edges: [edge('e1', 'n1', 'n2'), edge('e2', 'n2', 'n3'), edge('e3', 'n3', 'n4', 'Yes'), edge('e4', 'n3', 'n5', 'No')],
  };
}

// entry fans out to three checkpoints: everyone follows every arm.
function fanOutGraph(): DripGraph {
  return {
    rootId: 'n1',
    nodes: {
      n1: node('n1', 'ENTRY_SEGMENT', 'Everyone'),
      m1: node('m1', 'PAUSE', 'Month 1'),
      m2: node('m2', 'PAUSE', 'Month 3'),
      m3: node('m3', 'PAUSE', 'Month 6'),
    },
    edges: [edge('e1', 'n1', 'm1', 'Month 1'), edge('e2', 'n1', 'm2', 'Month 3'), edge('e3', 'n1', 'm3', 'Month 6')],
  };
}

const METRICS = {
  nodeCounts: { n1: 10000, n2: 9000, n3: 9000, n4: 2100, n5: 6900, m1: 10000, m2: 10000, m3: 10000 },
  edgeCounts: {
    e1: { count: 9000, pct: 100 },
    e2: { count: 9000, pct: 100 },
    e3: { count: 2100, pct: 23 },
    e4: { count: 6900, pct: 77 },
  },
  waitingByNodeId: { n2: 450 },
};

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function edgeData(els: ReturnType<typeof graphToFlowElements>, id: string): any {
  return els.edges.find((e) => e.id === id)?.data;
}
// eslint-disable-next-line @typescript-eslint/no-explicit-any
function nodeData(els: ReturnType<typeof graphToFlowElements>, id: string): any {
  return els.nodes.find((n) => n.id === id)?.data;
}

describe('what the journey shows on Analytics', () => {
  it('a step carries one count: how many reached it', () => {
    const els = graphToFlowElements(routingGraph(), { editable: false, metrics: METRICS });
    expect(nodeData(els, 'n1').stat).toBe('10,000 reached');
    expect(nodeData(els, 'n3').stat).toBe('9,000 reached');
  });

  it('a wait also shows how many are still waiting there, and nothing else does', () => {
    const els = graphToFlowElements(routingGraph(), { editable: false, metrics: METRICS });
    expect(nodeData(els, 'n2').engagement).toBe('450 still waiting');
    expect(nodeData(els, 'n3').engagement).toBeUndefined();
  });

  it('a step that divides people writes the split on its arrows, as a count with no percentage', () => {
    const els = graphToFlowElements(routingGraph(), { editable: false, metrics: METRICS });
    expect(edgeData(els, 'e3').statLabel).toBe('2,100');
    expect(edgeData(els, 'e4').statLabel).toBe('6,900');
    // The arrow already carries Yes / No; together they read "Yes 2,100".
    expect(edgeData(els, 'e3').branchLabel).toBe('Yes');
    for (const id of ['e1', 'e2', 'e3', 'e4']) expect(edgeData(els, id).statLabel ?? '').not.toContain('%');
  });

  it('a straight arrow carries nothing: there is no split to describe', () => {
    const els = graphToFlowElements(routingGraph(), { editable: false, metrics: METRICS });
    expect(edgeData(els, 'e1').statLabel).toBeUndefined();
    expect(edgeData(els, 'e2').statLabel).toBeUndefined();
  });

  it('arms that everyone follows show the full count on the step and nothing on the arrow', () => {
    const els = graphToFlowElements(fanOutGraph(), {
      editable: false,
      metrics: { nodeCounts: METRICS.nodeCounts, edgeCounts: { e1: { count: 10000, pct: 100 }, e2: { count: 10000, pct: 100 }, e3: { count: 10000, pct: 100 } } },
    });
    for (const id of ['m1', 'm2', 'm3']) expect(nodeData(els, id).stat).toBe('10,000 reached');
    for (const id of ['e1', 'e2', 'e3']) expect(edgeData(els, id).statLabel).toBeUndefined();
  });
});

describe('the two totals', () => {
  it('the held-back group reaches the goal at a lower rate than the messaged group', () => {
    for (const c of DRIP_CAMPAIGNS) {
      const { totals } = generateDripAnalytics(c);
      if (!totals.entered || !totals.control) continue;
      const messagedRate = totals.reachedGoal / totals.entered;
      const heldBackRate = totals.controlReachedGoal / totals.control;
      expect(heldBackRate).toBeLessThan(messagedRate);
      expect(totals.controlReachedGoal).toBeGreaterThanOrEqual(0);
    }
  });

  it('is deterministic, like every other seeded number here', () => {
    const a = generateDripAnalytics(DRIP_CAMPAIGNS[0]).totals.controlReachedGoal;
    const b = generateDripAnalytics(DRIP_CAMPAIGNS[0]).totals.controlReachedGoal;
    expect(a).toBe(b);
  });
});

describe('following one path', () => {
  it('reads from the start, through the chosen arrow, to where it ends', () => {
    const g = routingGraph();
    const path = dcPathThroughEdge(g, 'e4'); // the No arrow
    expect(path.nodeIds).toEqual(['n1', 'n2', 'n3', 'n5']);
    expect(path.edgeIds).toEqual(['e1', 'e2', 'e4']);
    // The arm not taken is off the path, so it fades.
    expect(path.edgeIds).not.toContain('e3');
    expect(path.nodeIds).not.toContain('n4');
  });

  it('stops at the next fork, where the arrow stops saying where anyone went', () => {
    const g = routingGraph();
    g.edges.push(edge('e5', 'n5', null));
    const path = dcPathThroughEdge(g, 'e1');
    expect(path.nodeIds).toEqual(['n1', 'n2', 'n3']);
  });

  it('an unknown edge selects nothing rather than throwing', () => {
    expect(dcPathThroughEdge(routingGraph(), 'nope')).toEqual({ nodeIds: [], edgeIds: [] });
  });
});
