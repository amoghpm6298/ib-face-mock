const EMPTY_GRAPH: DripGraph = { nodes: {}, edges: [], rootId: null };

function addEntryEvent(graph: DripGraph, overrides: Record<string, unknown> = {}): DripGraph {
  const p = { ...dcDefaultConfig('ENTRY_EVENT', null), eventCategory: 'Journey Events', eventType: 'Pageload', ...overrides };
  return dcConfirmAddNode(graph, 'ENTRY_EVENT', p, { kind: 'root' }, null);
}

beforeEach(() => {
  dcResetIdCounters();
});

describe('Entry nodes', () => {
  it('Entry Segment with a real condition', () => {
    const p = { ...dcDefaultConfig('ENTRY_SEGMENT', null), conditions: [{ attribute: 'Status', operator: 'Equals', value: 'Active' }] };
    const g = dcConfirmAddNode(EMPTY_GRAPH, 'ENTRY_SEGMENT', p, { kind: 'root' }, null);
    expect(g.rootId).toBeTruthy();
    const root = g.nodes[g.rootId!];
    expect(root.type).toBe('ENTRY_SEGMENT');
    expect(root.meta).toContain('Status = Active');
  });

  it('Entry Event sets the root', () => {
    const g = addEntryEvent(EMPTY_GRAPH);
    expect(g.rootId).toBeTruthy();
    expect(g.nodes[g.rootId!].type).toBe('ENTRY_EVENT');
  });

  it('Entry Scheduled with audience condition composes meta correctly', () => {
    const p = { ...dcDefaultConfig('ENTRY_SCHEDULED', null), entity: 'Account', conditions: [{ attribute: 'Status', operator: 'Equals', value: 'Active' }] };
    const g = dcConfirmAddNode(EMPTY_GRAPH, 'ENTRY_SCHEDULED', p, { kind: 'root' }, null);
    const root = g.nodes[g.rootId!];
    expect(root.meta).toContain('Account');
    expect(root.meta).not.toContain('undefined');
  });
});

describe('Send -> auto goal-check', () => {
  it('Send auto-inserts a Split + GOAL_EXIT, both resolve independently when chained with Channel Failover', () => {
    let g = addEntryEvent(EMPTY_GRAPH);
    const sendP = { ...dcDefaultConfig('SEND', null), name: 'Msg1', channel: 'WHATSAPP', account: 'IBL-Karix-Onb', templateId: 'CT-3310' };
    g = dcConfirmAddNode(g, 'SEND', sendP, { kind: 'growLeaf', nodeId: g.rootId! }, null);
    expect(Object.keys(g.nodes).length).toBeGreaterThanOrEqual(3); // Entry + Send + auto Split (+ GOAL_EXIT)

    const send = Object.values(g.nodes).find((n) => n.label === 'Msg1')!;
    const splitEdge = g.edges.find((e) => e.from === send.id)!;
    const split = g.nodes[splitEdge.to!];
    expect(split.type).toBe('SPLIT');
    expect(split.autoGenerated).toBe(false);
    const yesEdge = g.edges.find((e) => e.from === split.id && e.branchLabel === 'Yes')!;
    expect(g.nodes[yesEdge.to!].type).toBe('GOAL_EXIT');

    const noEdge = g.edges.find((e) => e.from === split.id && e.branchLabel === 'No')!;
    expect(noEdge.to).toBeNull();

    // chain Channel Failover under the No branch
    const cfP = { ...dcDefaultConfig('CHANNEL_FAILOVER', null), primaryChannel: 'WHATSAPP', fallbackChannel: 'SMS', account: 'IBL-Karix-Txns', templateId: 'CT-3301' };
    g = dcConfirmAddNode(g, 'CHANNEL_FAILOVER', cfP, { kind: 'edge', edgeId: noEdge.id }, null);
    const cfNode = Object.values(g.nodes).find((n) => n.type === 'CHANNEL_FAILOVER')!;
    const cfSplitEdge = g.edges.find((e) => e.from === cfNode.id)!;
    expect(g.nodes[cfSplitEdge.to!].type).toBe('SPLIT');
  });
});

