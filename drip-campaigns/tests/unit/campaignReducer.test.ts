describe('Connect to an existing step', () => {
  it('merging into an existing node adds one edge, creates no new node', () => {
    let g = addEntryEvent(EMPTY_GRAPH);
    const sendP = { ...dcDefaultConfig('SEND', null), name: 'Shared', channel: 'WHATSAPP', account: 'IBL-Karix-Onb', templateId: 'CT-3310' };
    g = dcConfirmAddNode(g, 'SEND', sendP, { kind: 'growLeaf', nodeId: g.rootId! }, null);
    const shared = Object.values(g.nodes).find((n) => n.label === 'Shared')!;
    const send = Object.values(g.nodes).find((n) => n.type === 'SPLIT')!;
    const noEdge = g.edges.find((e) => e.from === send.id && e.branchLabel === 'No')!;
    const beforeNodeCount = Object.keys(g.nodes).length;
    g = dcConnectExisting(g, { kind: 'edge', edgeId: noEdge.id }, shared.id);
    expect(Object.keys(g.nodes).length).toBe(beforeNodeCount); // no new node
    expect(g.edges.filter((e) => e.to === shared.id).length).toBe(2); // now reached from 2 places
  });
});
